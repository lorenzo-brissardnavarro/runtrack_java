class Division {
    public static void main(String[] args) {
        int nb1 = 3, nb2 = 73;
        System.out.println(nb2 + " / " + nb1 + " = " + (double) nb2 / nb1); // on obtient le resultat sous forme de double pour avoir les virgules
        System.out.println(nb1 + " / " + nb2 + " = " + (double) nb1 / nb2); // on obtient le resultat sous forme de double pour avoir les virgules
    }
}